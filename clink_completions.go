// quoteClinkLua quotes UTF-8 bytes without using Go-only Unicode escapes.
func quoteClinkLua(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '\\' || c == '"':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c < 32 || c >= 127:
			fmt.Fprintf(&b, "\\%03d", c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// GenClinkCompletion generates a standalone Clink Lua completion script.
// Clink provides completion for cmd.exe on Windows. The script queries the
// executable at completion time and does not require a separate Lua module.
// includeDesc controls whether completion descriptions are requested.
func (c *Command) GenClinkCompletion(w io.Writer, includeDesc bool) error {
	request := ShellCompRequestCmd
	if !includeDesc {
		request = ShellCompNoDescRequestCmd
	}
	env := activeHelpEnvVar(c.Name())
	script := strings.NewReplacer(
		"@NAME@", quoteClinkLua(strings.TrimSuffix(strings.ToLower(c.Name()), ".exe")),
		"@LABEL@", strings.NewReplacer("\r", " ", "\n", " ").Replace(c.Name()),
		"@REQUEST@", quoteClinkLua(request),
		"@ACTIVE_HELP@", quoteClinkLua(env),
	).Replace(clinkCompletionScript)
	_, err := io.WriteString(w, script)
	return err
}

// GenClinkCompletionFile writes a Clink Lua completion script to filename.
func (c *Command) GenClinkCompletionFile(filename string, includeDesc bool) error {
	f, err := os.Create(filename)
	if err != nil {
		return err
	}
	defer f.Close()
	return c.GenClinkCompletion(f, includeDesc)
}

const clinkCompletionScript = `-- Clink completion for @LABEL@. Generated by Cobra.
-- Requires Clink 1.3.3 or newer; load from a Clink script directory.
-- Completion protocol shared by commands built with github.com/spf13/cobra.
local cobra = {}
local request_command = @REQUEST@
local active_help_env = @ACTIVE_HELP@

function cobra.quote(word)
    -- Clink strips quotes from getword() during generation. Reject any literal
    -- quote or control character defensively, and skip % and !, which cmd.exe
    -- may expand even inside quotes. Double trailing backslashes for native argv.
    if word:find('["%%!%c]') then return nil end
    return '"' .. word:gsub('(\\+)$', '%1%1') .. '"'
end

function cobra.command(executable, words)
    -- The quoting below is for an EXE. Bypass PATHEXT so a BAT or CMD script
    -- cannot be selected for a bare name and parse the arguments differently.
    if not executable:lower():match('%.exe$') then
        executable = executable .. '.exe'
    end
    local quoted = cobra.quote(executable)
    if not quoted then return nil end
    -- Keep the redirection before the quoted executable. Starting cmd.exe /C
    -- with a quote can strip outer quotes and expose shell metacharacters.
    local redirect = '2>nul'
    if not clink.hinter then
        redirect = 'set "' .. active_help_env .. '=0" & ' .. redirect
    end
    local args = { redirect, quoted, request_command }
    for _, word in ipairs(words) do
        quoted = cobra.quote(word)
        if not quoted then return nil end
        args[#args + 1] = quoted
    end
    return table.concat(args, ' ')
end

-- ShellCompDirective bits from completions.go.
local directive_bits = {
    error = 1,
    no_space = 2,
    no_file_completion = 4,
    filter_file_extensions = 8,
    filter_directories = 16,
    keep_order = 32,
}

function cobra.parse(lines)
    local directive = tonumber((lines[#lines] or ''):match('^:(%d+)$'))
    if not directive or directive > 63 then return nil end
    local matches, help = {}, {}
    for i = 1, #lines - 1 do
        local line = lines[i]
        if line:sub(1, 12) == '_activeHelp_' then
            help[#help + 1] = line:sub(13):gsub('^%s+', '')
        elseif line ~= '' then
            local value, description = line:match('^([^\t]+)\t(.*)$')
            matches[#matches + 1] = { match=value or line, description=description }
        end
    end
    local directives = {}
    for name, bit in pairs(directive_bits) do
        directives[name] = directive % (bit * 2) >= bit
    end
    return { matches=matches, directives=directives, help=table.concat(help, ' | ') }
end

function cobra.apply(result, word, builder)
    if not result then return false end
    local directives = result.directives
    if directives.error then return true end
    if directives.no_space then builder:setsuppressappend() end
    if directives.keep_order then builder:setnosort() end
    if directives.filter_directories then
        -- Cobra can optionally name a directory whose children to complete.
        local root = result.matches[1] and result.matches[1].match
        local prefix = root and (root:gsub('[/\\]+$', '') .. '\\') or ''
        for _, match in ipairs(clink.dirmatches(prefix .. word)) do
            if prefix ~= '' then
                if type(match) == 'table' then
                    match.match = match.match:sub(#prefix + 1)
                else
                    match = match:sub(#prefix + 1)
                end
            end
            builder:addmatch(match, 'dir')
        end
        return true
    end
    if directives.filter_file_extensions then
        for _, match in ipairs(clink.filematches(word)) do
            local name = type(match) == 'table' and match.match or match
            local isdir = name:find('[/\\]$') or
                (type(match) == 'table' and (match.type or ''):find('dir', 1, true))
            local accept = isdir
            for _, ext in ipairs(result.matches) do
                local suffix = '.' .. ext.match:gsub('^%.', ''):lower()
                if name:lower():sub(-#suffix) == suffix then accept = true end
            end
            if accept then builder:addmatch(match, isdir and 'dir' or 'file') end
        end
        return true
    end
    builder:addmatches(result.matches)
    return #result.matches > 0 or directives.no_file_completion
end

function cobra.register(name)
    if (clink.version_encoded or 0) < 10030003 then return end
    local cache = {}
    local hint_line, hint
    clink.onbeginedit(function() cache = {}; hint_line = nil; hint = nil end)
    if clink.hinter then
        local hinter = clink.hinter(24)
        function hinter:gethint(line_state) -- luacheck: no unused
            if hint_line == line_state:getline():sub(1, line_state:getcursor() - 1) then
                return hint
            end
        end
    end
    local generator = clink.generator(24)
    local function is_command(line_state)
        local index = line_state:getcommandwordindex()
        if line_state:getwordcount() <= index then return false end
        local word = line_state:getword(index)
        -- Clink leaves surrounding quotes intact during getwordbreakinfo().
        word = word:gsub('^"', ''):gsub('"$', '')
        return (word:match('[^/\\]+$') or word):lower():gsub('%.exe$', '') == name
    end
    function generator:getwordbreakinfo(line_state) -- luacheck: no unused
        if is_command(line_state) then
            -- Cobra needs the prefix, including '=' and ':' in flag/FQBN values.
            return 0, #line_state:getendword()
        end
    end
    function generator:generate(line_state, builder) -- luacheck: no unused
        if not is_command(line_state) then return false end
        local previous_line, previous_hint = hint_line, hint
        hint_line, hint = nil, nil
        local first = line_state:getcommandwordindex()
        local words = {}
        local previous
        for i = first + 1, line_state:getwordcount() do
            local info = line_state:getwordinfo(i)
            if not info.redir then
                local word = line_state:getword(i)
                local start = info.offset - (info.quoted and 1 or 0)
                local gap = previous and line_state:getline():sub(previous, start - 1)
                -- cmd word breaking also splits unquoted key=value,comma lists.
                -- They remain one argv entry unless separated by whitespace.
                if gap and gap:match('^[=,;]*$') then
                    words[#words] = words[#words] .. gap .. word
                else
                    words[#words + 1] = word
                end
                previous = info.offset + info.length + (info.quoted and 1 or 0)
            else
                previous = nil
            end
        end
        local last = line_state:getwordinfo(line_state:getwordcount())
        if last.redir then return false end
        if #words == 0 then words[1] = '' end
        local command = cobra.command(line_state:getword(first), words)
        if not command then return true end
        local result = cache[command]
        if result == nil then
            local pipe = io.popen(command)
            if not pipe then return false end
            local lines = {}
            for line in pipe:lines() do lines[#lines + 1] = line end
            local ok = pipe:close()
            result = ok and cobra.parse(lines) or false
            cache[command] = result
        end
        if result and not result.directives.error and result.help ~= '' then
            hint_line = line_state:getline():sub(1, line_state:getcursor() - 1)
            hint = result.help
        end
        -- Hinters are normally called only when the input changes. Refresh them
        -- after an asynchronous completion result arrives, without rerunning it.
        if clink.hinter and clink.reclassifyline and
                (hint_line ~= previous_line or hint ~= previous_hint) then
            clink.reclassifyline()
        end
        return cobra.apply(result, line_state:getendword(), builder)
    end
    return generator
end

cobra.register(@NAME@)
`
