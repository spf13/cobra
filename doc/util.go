package doc

import (
	"strings"

	"github.com/spf13/cobra"
)

// filenameForCommand builds a filesystem-safe basename for the given command
// path. CommandPath() joins command names with spaces, and individual command
// names may themselves contain path separators (e.g. "job/first"), which
// filepath.Join would turn into spurious subdirectories and cause os.Create to
// fail with "no such file or directory". We collapse both spaces and slashes
// into the given separator so the result is a single filename component.
func filenameForCommand(cmd *cobra.Command, separator string) string {
	replacer := strings.NewReplacer(" ", separator, "/", separator)
	return replacer.Replace(cmd.CommandPath())
}

// Test to see if we have a reason to print See Also information in docs
// Basically this is a test for a parent command or a subcommand which is
// both not deprecated and not the autogenerated help command.
func hasSeeAlso(cmd *cobra.Command) bool {
	if cmd.HasParent() {
		return true
	}
	for _, c := range cmd.Commands() {
		if !c.IsAvailableCommand() || c.IsAdditionalHelpTopicCommand() {
			continue
		}
		return true
	}
	return false
}

// Temporary workaround for yaml lib generating incorrect yaml with long strings
// that do not contain \n.
func forceMultiLine(s string) string {
	if len(s) > 60 && !strings.Contains(s, "\n") {
		s += "\n"
	}
	return s
}

type byName []*cobra.Command

func (s byName) Len() int           { return len(s) }
func (s byName) Swap(i, j int)      { s[i], s[j] = s[j], s[i] }
func (s byName) Less(i, j int) bool { return s[i].Name() < s[j].Name() }
